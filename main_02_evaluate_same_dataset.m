clear; clc;

%% USER SETTINGS
projectRoot = fileparts(mfilename('fullpath'));
addpath(fullfile(projectRoot, 'functions'));

resultsFolder = fullfile(projectRoot, 'results');
if ~isfolder(resultsFolder), mkdir(resultsFolder); end

% Choose: 'binary' or 'correlation'
config.analysisType = 'binary';

config.developmentFile = fullfile( ...
    projectRoot, 'data', 'development_dataset.mat');

% Leave empty to auto-resolve when exactly one matching step-1 file exists.
% Otherwise provide the exact MAT-file path.
config.hyperparameterFile = '';

config.samplingRate = 500;
config.notchFrequencyHz = 60;
config.notchQualityFactor = 35;
config.useNormalizedProjection = false;

config.excludedChannels = {};

% Example 1:5 evaluates all 1-, 2-, 3-, 4-, and 5-channel combinations.
config.minimumCombinationSize = 1;
config.maximumCombinationSize = 5;

% All combinations are evaluated exactly, but only the top K per size are
% retained in memory and written to output.
config.topKPerSize = 1000;
config.combinationBatchSize = 10000;

config.useParallel = true;
config.numberOfWorkers = [];

%% CROSS-VALIDATION SETTINGS
% Keep these consistent with step 1.
% 1 = leave-one-out; integer >1 = K-fold.
config.numberOfFolds = 1;
config.randomSeed = 1;

%% ANALYSIS-SPECIFIC SETTINGS
switch lower(config.analysisType)

    case 'binary'
        config.foldFile = fullfile( ...
            resultsFolder, 'development_cv_folds_binary.mat');

        config.outputFile = fullfile( ...
            resultsFolder, 'same_dataset_evaluation_binary.mat');

        config.excelFile = fullfile( ...
            resultsFolder, 'same_dataset_evaluation_binary.xlsx');

    case 'correlation'
        config.foldFile = fullfile( ...
            resultsFolder, 'development_cv_folds_correlation.mat');

        config.targetFile = fullfile( ...
            projectRoot, 'data', 'development_targets.xlsx');

        config.subjectIDColumn = 'ID';
        config.targetColumn = 'Target';

        % 'min', 'max', or 'maxabs'
        config.selectionCriterion = 'max';

        targetLabel = matlab.lang.makeValidName(config.targetColumn);

        config.outputFile = fullfile( ...
            resultsFolder, ...
            sprintf('same_dataset_evaluation_correlation_%s.mat', ...
                targetLabel));

        config.excelFile = fullfile( ...
            resultsFolder, ...
            sprintf('same_dataset_evaluation_correlation_%s.xlsx', ...
                targetLabel));

    otherwise
        error('Unknown analysisType: "%s".', config.analysisType);
end

%% START PARALLEL POOL
if config.useParallel
    pool = gcp('nocreate');

    if isempty(pool)
        if isempty(config.numberOfWorkers)
            pool = parpool;
        else
            pool = parpool(config.numberOfWorkers);
        end
    end

    fprintf('\nParallel pool active with %d workers.\n', ...
        pool.NumWorkers);
end

%% LOAD FIXED CHANNEL-SPECIFIC HYPERPARAMETERS
config.hyperparameterFile = resolve_hyperparameter_file( ...
    resultsFolder, config.analysisType, config.hyperparameterFile);

fprintf('Using hyperparameter file:\n%s\n', ...
    config.hyperparameterFile);

% Reuse the CV settings that were actually used during hyperparameter
% selection whenever they are available in the step-1 MAT file.
step1Metadata = load(config.hyperparameterFile, 'config');
if isfield(step1Metadata, 'config')
    if isfield(step1Metadata.config, 'numberOfFolds')
        config.numberOfFolds = step1Metadata.config.numberOfFolds;
    end
    if isfield(step1Metadata.config, 'randomSeed')
        config.randomSeed = step1Metadata.config.randomSeed;
    end
end

fprintf('Using CV setting from step 1: numberOfFolds = %d, seed = %d\n', ...
    config.numberOfFolds, config.randomSeed);

candidateModels = load_candidate_models( ...
    config.hyperparameterFile, config.excludedChannels);

disp(candidateModels(:, { ...
    'Channel','LowCutoffHz','HighCutoffHz', ...
    'LPCOrder','PCADimension'}));

%% LOAD DEVELOPMENT DATA
developmentData = load_leapd_dataset(config.developmentFile);

switch lower(config.analysisType)

    case 'binary'
        [~, classes, subjectIDs] = ...
            get_binary_channel_data( ...
                developmentData, char(candidateModels.Channel(1)));

        [cvPartition, foldInfo] = load_or_create_cv_folds( ...
            subjectIDs, classes, ...
            config.numberOfFolds, ...
            config.randomSeed, ...
            config.foldFile);

        fprintf('Cross-validation folds: %s\n', foldInfo.message);

        channelIndices = build_binary_development_indices( ...
            developmentData, candidateModels, cvPartition, config);

        [combinationResults, bestBySize, bestScoreTable] = ...
            evaluate_binary_combinations( ...
                channelIndices, ...
                classes, ...
                subjectIDs, ...
                string(candidateModels.Channel), ...
                config.minimumCombinationSize, ...
                config.maximumCombinationSize, ...
                config.topKPerSize, ...
                config.combinationBatchSize, ...
                config.useParallel);

        save(config.outputFile, ...
            'combinationResults', ...
            'bestBySize', ...
            'bestScoreTable', ...
            'candidateModels', ...
            'channelIndices', ...
            'classes', ...
            'subjectIDs', ...
            'config', ...
            '-v7.3');

        writetable(combinationResults, ...
            config.excelFile, 'Sheet', 'Top_Combinations');

        writetable(bestBySize, ...
            config.excelFile, 'Sheet', 'Best_By_Size');

        writetable(bestScoreTable, ...
            config.excelFile, 'Sheet', 'Best_Subject_Indices');

        fprintf('\nBest results within each requested model size:\n');
        disp(bestBySize(:, { ...
            'NumberOfChannels','Channels','Accuracy', ...
            'BalancedAccuracy','Sensitivity','Specificity'}));

    case 'correlation'
        firstChannel = get_channel_data( ...
            developmentData, char(candidateModels.Channel(1)));

        targetData = load_correlation_targets( ...
            config.targetFile, ...
            config.subjectIDColumn, ...
            config.targetColumn);

        targetValues = match_correlation_targets( ...
            firstChannel.group1IDs, targetData, true);

        [cvPartition, foldInfo] = ...
            load_or_create_correlation_cv_folds( ...
                firstChannel.group1IDs, ...
                config.numberOfFolds, ...
                config.randomSeed, ...
                config.foldFile);

        fprintf('Cross-validation folds: %s\n', foldInfo.message);

        [channelIndices, subjectIDs] = ...
            build_correlation_development_indices( ...
                developmentData, candidateModels, ...
                cvPartition, config);

        [combinationResults, bestBySize, bestScoreTable] = ...
            evaluate_correlation_combinations( ...
                channelIndices, ...
                targetValues, ...
                subjectIDs, ...
                string(candidateModels.Channel), ...
                config.minimumCombinationSize, ...
                config.maximumCombinationSize, ...
                config.selectionCriterion, ...
                config.topKPerSize, ...
                config.combinationBatchSize, ...
                config.useParallel);

        save(config.outputFile, ...
            'combinationResults', ...
            'bestBySize', ...
            'bestScoreTable', ...
            'candidateModels', ...
            'channelIndices', ...
            'subjectIDs', ...
            'targetValues', ...
            'config', ...
            '-v7.3');

        writetable(combinationResults, ...
            config.excelFile, 'Sheet', 'Top_Combinations');

        writetable(bestBySize, ...
            config.excelFile, 'Sheet', 'Best_By_Size');

        writetable(bestScoreTable, ...
            config.excelFile, 'Sheet', 'Best_Combined_Indices');

        fprintf('\nBest results within each requested model size:\n');
        disp(bestBySize(:, { ...
            'NumberOfChannels','Channels', ...
            'SpearmanRho','PValue','NValid'}));
end

fprintf('\nSaved MAT results to:\n%s\n', config.outputFile);
fprintf('\nSaved Excel results to:\n%s\n', config.excelFile);
