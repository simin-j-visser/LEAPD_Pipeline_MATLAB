function results = evaluate_binary_combinations( ...
    combos, ...
    logScores, ...
    trueClasses, ...
    subjectWeights, ...
    channelNames, ...
    batchSize)

    nCombos = ...
        size(combos,1);


    combinationSize = ...
        size(combos,2);


    meanAccuracy = ...
        nan(nCombos,1);


    threshold = ...
        combinationSize * log(0.5);


    for firstRow = 1:batchSize:nCombos

        lastRow = ...
            min( ...
                firstRow + batchSize - 1, ...
                nCombos);


        batchCombos = ...
            combos(firstRow:lastRow,:);


        nBatch = ...
            size(batchCombos,1);


        combinedLogScores = ...
            zeros( ...
                nBatch, ...
                size(logScores,2));


        for k = 1:combinationSize

            combinedLogScores = ...
                combinedLogScores + ...
                logScores( ...
                    batchCombos(:,k), ...
                    :);

        end


        predictions = ...
            combinedLogScores > threshold;


        class1Mask = ...
            trueClasses(:)' == 1;


        class0Mask = ...
            trueClasses(:)' == 0;


        correct = ...
            false(size(predictions));


        correct(:,class1Mask) = ...
            predictions(:,class1Mask);


        correct(:,class0Mask) = ...
            ~predictions(:,class0Mask);


        meanAccuracy(firstRow:lastRow) = ...
            double(correct) * ...
            subjectWeights(:);

    end


    channelCells = ...
        mat2cell( ...
            combos, ...
            ones(nCombos,1), ...
            combinationSize);


    channelStrings = ...
        strings(nCombos,1);


    for i = 1:nCombos

        channelStrings(i) = ...
            strjoin( ...
                channelNames(combos(i,:)), ...
                ', ');

    end


    results = ...
        table( ...
            channelCells, ...
            channelStrings, ...
            meanAccuracy, ...
            'VariableNames', { ...
                'ChannelIndices', ...
                'Channels', ...
                'MeanAccuracy'});

end


function retained = retain_beam_with_ties( ...
    results, ...
    beamWidth, ...
    maximumBeamRetained, ...
    tolerance)

    n = ...
        height(results);


    if n <= beamWidth

        retained = ...
            results;

        return;

    end


    cutoff = ...
        results.MeanAccuracy(beamWidth);


    keep = ...
        results.MeanAccuracy >= ...
        cutoff - tolerance;


    numberToKeep = ...
        sum(keep);


    if numberToKeep > maximumBeamRetained

        fprintf( ...
            ['Tie-aware beam wanted %d candidates; ' ...
             'capping at %d.\n'], ...
            numberToKeep, ...
            maximumBeamRetained);


        retained = ...
            results(1:maximumBeamRetained,:);

    else

        retained = ...
            results(keep,:);

    end

end


function topResults = exhaustive_five_binary( ...
    logScores, ...
    trueClasses, ...
    subjectWeights, ...
    channelNames, ...
    beamWidth, ...
    maximumBeamRetained, ...
    tieTolerance, ...
    batchSize)

    nChannels = ...
        size(logScores,1);


    total = ...
        nchoosek(nChannels,5);


    processed = ...
        0;


    topResults = ...
        table();


    timer = ...
        tic;


    fprintf( ...
        'Total combinations: %.0f\n', ...
        total);


    for firstChannel = 1:(nChannels-4)

        tails = ...
            nchoosek( ...
                (firstChannel+1):nChannels, ...
                4);


        combos = ...
            [ ...
                repmat( ...
                    firstChannel, ...
                    size(tails,1), ...
                    1), ...
                tails ...
            ];


        current = ...
            evaluate_binary_combinations( ...
                combos, ...
                logScores, ...
                trueClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);


        current = ...
            sortrows( ...
                current, ...
                'MeanAccuracy', ...
                'descend');


        current = ...
            retain_beam_with_ties( ...
                current, ...
                min(beamWidth,height(current)), ...
                maximumBeamRetained, ...
                tieTolerance);


        if isempty(topResults)

            topResults = ...
                current;

        else

            topResults = ...
                [topResults; current];


            topResults = ...
                sortrows( ...
                    topResults, ...
                    'MeanAccuracy', ...
                    'descend');


            topResults = ...
                retain_beam_with_ties( ...
                    topResults, ...
                    min(beamWidth,height(topResults)), ...
                    maximumBeamRetained, ...
                    tieTolerance);

        end


        processed = ...
            processed + ...
            size(combos,1);


        elapsed = ...
            toc(timer);


        fraction = ...
            processed / total;


        remaining = ...
            elapsed/fraction - elapsed;


        fprintf( ...
            ['First channel %2d/%2d | ' ...
             '%6.2f%% | elapsed %.1f min | remaining %.1f min\n'], ...
            firstChannel, ...
            nChannels-4, ...
            100*fraction, ...
            elapsed/60, ...
            remaining/60);

    end

end


function candidateCombos = expand_binary_beam( ...
    previousTop, ...
    nChannels)

    candidateCell = ...
        cell(0,1);


    counter = 0;


    for i = 1:height(previousTop)

        base = ...
            previousTop.ChannelIndices{i};


        available = ...
            setdiff( ...
                1:nChannels, ...
                base);


        for ch = available

            counter = ...
                counter + 1;


            candidateCell{counter,1} = ...
                sort([base ch]);

        end

    end


    candidateCombos = ...
        unique( ...
            vertcat(candidateCell{:}), ...
            'rows');

end


function result = iterative_one_swap_binary( ...
    startCombo, ...
    logScores, ...
    trueClasses, ...
    subjectWeights, ...
    channelNames, ...
    batchSize)

    currentCombo = ...
        sort(startCombo);


    current = ...
        evaluate_binary_combinations( ...
            currentCombo, ...
            logScores, ...
            trueClasses, ...
            subjectWeights, ...
            channelNames, ...
            batchSize);


    iterations = 0;


    while true

        nChannels = ...
            size(logScores,1);


        outside = ...
            setdiff( ...
                1:nChannels, ...
                currentCombo);


        candidates = ...
            zeros( ...
                numel(currentCombo)*numel(outside), ...
                numel(currentCombo));


        row = 0;


        for removePosition = 1:numel(currentCombo)

            for addChannel = outside

                row = row + 1;


                candidate = ...
                    currentCombo;


                candidate(removePosition) = ...
                    addChannel;


                candidates(row,:) = ...
                    sort(candidate);

            end

        end


        candidates = ...
            unique( ...
                candidates, ...
                'rows');


        evaluated = ...
            evaluate_binary_combinations( ...
                candidates, ...
                logScores, ...
                trueClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);


        evaluated = ...
            sortrows( ...
                evaluated, ...
                'MeanAccuracy', ...
                'descend');


        if evaluated.MeanAccuracy(1) > ...
                current.MeanAccuracy(1) + 1e-12

            current = ...
                evaluated(1,:);


            currentCombo = ...
                current.ChannelIndices{1};


            iterations = ...
                iterations + 1;

        else

            break;

        end

    end


    result = ...
        current;


    result.OneSwapIterations = ...
        iterations;

end


function result = best_two_swap_binary( ...
    startCombo, ...
    logScores, ...
    trueClasses, ...
    subjectWeights, ...
    channelNames, ...
    batchSize)

    startCombo = ...
        sort(startCombo);


    current = ...
        evaluate_binary_combinations( ...
            startCombo, ...
            logScores, ...
            trueClasses, ...
            subjectWeights, ...
            channelNames, ...
            batchSize);


    nChannels = ...
        size(logScores,1);


    outside = ...
        setdiff( ...
            1:nChannels, ...
            startCombo);


    removePairs = ...
        nchoosek( ...
            1:numel(startCombo), ...
            2);


    addPairs = ...
        nchoosek( ...
            outside, ...
            2);


    nCandidates = ...
        size(removePairs,1) * ...
        size(addPairs,1);


    candidates = ...
        zeros( ...
            nCandidates, ...
            numel(startCombo));


    row = 0;


    for r = 1:size(removePairs,1)

        for a = 1:size(addPairs,1)

            row = row + 1;


            candidate = ...
                startCombo;


            candidate(removePairs(r,:)) = ...
                addPairs(a,:);


            candidates(row,:) = ...
                sort(candidate);

        end

    end


    candidates = ...
        unique( ...
            candidates, ...
            'rows');


    evaluated = ...
        evaluate_binary_combinations( ...
            candidates, ...
            logScores, ...
            trueClasses, ...
            subjectWeights, ...
            channelNames, ...
            batchSize);


    evaluated = ...
        sortrows( ...
            evaluated, ...
            'MeanAccuracy', ...
            'descend');


    if evaluated.MeanAccuracy(1) > ...
            current.MeanAccuracy(1) + 1e-12

        result = ...
            evaluated(1,:);


        result.TwoSwapImproved = ...
            true;

    else

        result = ...
            current;


        result.TwoSwapImproved = ...
            false;

    end

end


