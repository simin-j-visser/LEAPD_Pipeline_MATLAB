%% ============================================================
% SETTINGS
% ============================================================

% These settings are specific to the OOS combination search.
% Preprocessing/model settings used during development
% (sampling rate, notch settings, projection option) are loaded
% directly from the saved hyperparameter-search config below.

useParallel = true;

numberOfRepeats = 10000;

subjectsPerClass = 13;

randomSeed = 1;


% ------------------------
% ENHANCED SEARCH SETTINGS
% ------------------------

beamWidth = 1000;

% Keep ties at beam cutoff, but avoid pathological explosion.
maximumBeamRetained = 5000;

tieTolerance = 1e-12;


% One-swap refinement:
localSwapTopN = 100;


% Two-swap refinement:
twoSwapTopN = 20;


% Batch size for vectorized candidate scoring.
% Lower if RAM becomes limiting.
batchSize = 5000;


%% ============================================================
% VERIFY FILES
% ============================================================

if ~isfile(developmentFile)
    error('Development file not found:\n%s', developmentFile);
end

if ~isfile(testFile)
    error('Test file not found:\n%s', testFile);
end

if ~isfile(hyperparameterFile)
    error('Hyperparameter file not found:\n%s', hyperparameterFile);
end


%% ============================================================
% PARALLEL POOL
% ============================================================

if useParallel

    pool = gcp('nocreate');

    if isempty(pool)
        pool = parpool;
    end

    % Make all external LEAPD helper functions explicitly available
    % to the workers before any parfor block begins.
    functionInfo = dir(fullfile(functionsFolder, '*.m'));

    functionFiles = fullfile( ...
        {functionInfo.folder}, ...
        {functionInfo.name});

    addAttachedFiles(pool, functionFiles);

    fprintf('\nParallel workers: %d\n', pool.NumWorkers);

end


%% ============================================================
% LOAD DEVELOPMENT HYPERPARAMETERS + PREPROCESSING SETTINGS
% ============================================================

fprintf('\n============================================================\n');
fprintf('LOADING DEVELOPMENT PARAMETERS\n');
fprintf('============================================================\n');

candidateModels = ...
    load_candidate_models( ...
        hyperparameterFile, ...
        {});

hyperparameterData = ...
    load( ...
        hyperparameterFile, ...
        'config');

if ~isfield(hyperparameterData, 'config')

    error( ...
        ['The hyperparameter result file does not contain ' ...
         'the saved development config.']);

end

trainingConfig = ...
    hyperparameterData.config;

% Use the same basic settings as the development hyperparameter search.
if isfield(trainingConfig, 'samplingRate')
    samplingRate = trainingConfig.samplingRate;
else
    samplingRate = 500;
    warning('samplingRate was not saved in config. Using default 500 Hz.');
end

% The GitHub-optimized training pipeline should save these fields.
% If an older result file does not contain them, the code falls back to
% the intended TBI scalp EEG line-noise settings used in this project.
if isfield(trainingConfig, 'notchFrequencyHz')
    notchFrequencyHz = trainingConfig.notchFrequencyHz;
else
    notchFrequencyHz = 60;
    warning(['notchFrequencyHz was not saved in config. ' ...
             'Using default 60 Hz. Make sure the training run used the same setting.']);
end

if isfield(trainingConfig, 'notchQualityFactor')
    notchQualityFactor = trainingConfig.notchQualityFactor;
else
    notchQualityFactor = 35;
    warning(['notchQualityFactor was not saved in config. ' ...
             'Using default Q = 35. Make sure the training run used the same setting.']);
end

if isfield(trainingConfig, 'useNormalizedProjection')
    useNormalizedProjection = trainingConfig.useNormalizedProjection;
else
    useNormalizedProjection = false;
    warning('useNormalizedProjection was not saved in config. Using default false.');
end

nChannels = ...
    height(candidateModels);

channelNames = ...
    string(candidateModels.Channel(:));

fprintf('Channels: %d\n', nChannels);
fprintf('Sampling rate: %.1f Hz\n', samplingRate);
fprintf('Notch frequency: %.1f Hz\n', notchFrequencyHz);
fprintf('Notch quality factor: %.3f\n', notchQualityFactor);
fprintf('Normalized projection: %d\n', useNormalizedProjection);


%% ============================================================
% LOAD DEVELOPMENT + TEST DATA
% ============================================================

developmentData = ...
    load_leapd_dataset(developmentFile);


testData = ...
    load_leapd_dataset(testFile);


[~, developmentClasses, developmentSubjectIDs] = ...
    get_binary_channel_data( ...
        developmentData, ...
        char(candidateModels.Channel(1)));


[~, testClasses, testSubjectIDs] = ...
    get_binary_channel_data( ...
        testData, ...
        char(candidateModels.Channel(1)));


developmentClasses = ...
    developmentClasses(:);


testClasses = ...
    testClasses(:);


testSubjectIDs = ...
    cellstr(string(testSubjectIDs(:)));


nTBI = ...
    sum(testClasses == 1);


nControl = ...
    sum(testClasses == 0);


fprintf('\nAnalysis: %s\n', upper(analysisMode));

fprintf('Development subjects: %d\n', ...
    numel(developmentClasses));

fprintf('OOS subjects: %d\n', ...
    numel(testClasses));

fprintf('TBI class 1: %d\n', nTBI);

fprintf('Control class 0: %d\n', nControl);


if nControl ~= subjectsPerClass

    error( ...
        'Expected %d controls; found %d.', ...
        subjectsPerClass, ...
        nControl);

end


%% ============================================================
% VERIFY ORDER
%
% get_binary_channel_data guarantees:
%
%   class 1 first
%   class 0 second
% ============================================================

if ~all(testClasses(1:nTBI) == 1)

    error('Unexpected test subject ordering.');

end


if ~all(testClasses(nTBI+1:end) == 0)

    error('Unexpected control ordering.');

end


tbiRows = ...
    find(testClasses == 1);


controlRows = ...
    find(testClasses == 0);


%% ============================================================
% BUILD / LOAD SINGLE-CHANNEL SCORES
% ============================================================

fprintf('\n============================================================\n');
fprintf('SINGLE-CHANNEL LEAPD SCORES\n');
fprintf('============================================================\n');


rebuildScoreCache = true;


% Store the exact selected per-channel development parameters that
% determine feature extraction and LEAPD model fitting.
currentModelSignature = ...
    candidateModels(:, { ...
        'Channel', ...
        'LowCutoffHz', ...
        'HighCutoffHz', ...
        'LPCOrder', ...
        'PCADimension'});


%% ------------------------------------------------------------
% Check whether an existing score cache is fully compatible
% ------------------------------------------------------------

if isfile(scoreFile)

    fprintf('Checking existing score cache...\n');

    S = load(scoreFile);

    cacheCompatible = true;


    % Subject order
    if ~isfield(S, 'savedSubjectIDs') || ...
            ~isequal( ...
                string(S.savedSubjectIDs(:)), ...
                string(testSubjectIDs(:)))

        cacheCompatible = false;

    end


    % Channel order
    if ~isfield(S, 'savedChannelNames') || ...
            ~isequal( ...
                string(S.savedChannelNames(:)), ...
                channelNames(:))

        cacheCompatible = false;

    end


    % Exact selected hyperparameters
    if ~isfield(S, 'savedModelSignature') || ...
            ~isequaln( ...
                S.savedModelSignature, ...
                currentModelSignature)

        cacheCompatible = false;

    end


    % Sampling rate
    if ~isfield(S, 'savedSamplingRate') || ...
            ~isequaln( ...
                S.savedSamplingRate, ...
                samplingRate)

        cacheCompatible = false;

    end


    % Notch frequency
    if ~isfield(S, 'savedNotchFrequencyHz') || ...
            ~isequaln( ...
                S.savedNotchFrequencyHz, ...
                notchFrequencyHz)

        cacheCompatible = false;

    end


    % Notch quality factor
    if ~isfield(S, 'savedNotchQualityFactor') || ...
            ~isequaln( ...
                S.savedNotchQualityFactor, ...
                notchQualityFactor)

        cacheCompatible = false;

    end


    % LEAPD distance/projection definition
    if ~isfield(S, 'savedUseNormalizedProjection') || ...
            ~isequaln( ...
                S.savedUseNormalizedProjection, ...
                useNormalizedProjection)

        cacheCompatible = false;

    end


    if cacheCompatible

        fprintf('Compatible score cache found. Loading...\n');

        singleChannelScores = ...
            S.singleChannelScores;

        rebuildScoreCache = false;

    else

        fprintf([ ...
            'Existing score cache does not match the current ' ...
            'development settings and will be rebuilt.\n']);

    end

end


%% ------------------------------------------------------------
% Build single-channel OOS scores when needed
% ------------------------------------------------------------

if rebuildScoreCache

    fprintf('Building development features...\n');

    developmentFeatures = ...
        build_selected_channel_features( ...
            developmentData, ...
            candidateModels, ...
            samplingRate, ...
            notchFrequencyHz, ...
            notchQualityFactor);


    fprintf('Building OOS features...\n');

    testFeatures = ...
        build_selected_channel_features( ...
            testData, ...
            candidateModels, ...
            samplingRate, ...
            notchFrequencyHz, ...
            notchQualityFactor);


    singleChannelScores = ...
        nan( ...
            nChannels, ...
            numel(testClasses));


    if useParallel

        parfor ch = 1:nChannels

            model = ...
                fit_leapd_model( ...
                    developmentFeatures{ch}, ...
                    developmentClasses, ...
                    candidateModels.PCADimension(ch));


            scores = ...
                predict_leapd_model( ...
                    model, ...
                    testFeatures{ch}, ...
                    useNormalizedProjection);


            singleChannelScores(ch,:) = ...
                scores(:)';

        end

    else

        for ch = 1:nChannels

            model = ...
                fit_leapd_model( ...
                    developmentFeatures{ch}, ...
                    developmentClasses, ...
                    candidateModels.PCADimension(ch));


            scores = ...
                predict_leapd_model( ...
                    model, ...
                    testFeatures{ch}, ...
                    useNormalizedProjection);


            singleChannelScores(ch,:) = ...
                scores(:)';

        end

    end


    savedSubjectIDs = ...
        testSubjectIDs;


    savedChannelNames = ...
        channelNames;


    savedModelSignature = ...
        currentModelSignature;


    savedSamplingRate = ...
        samplingRate;


    savedNotchFrequencyHz = ...
        notchFrequencyHz;


    savedNotchQualityFactor = ...
        notchQualityFactor;


    savedUseNormalizedProjection = ...
        useNormalizedProjection;


    save( ...
        scoreFile, ...
        'singleChannelScores', ...
        'savedSubjectIDs', ...
        'savedChannelNames', ...
        'savedModelSignature', ...
        'savedSamplingRate', ...
        'savedNotchFrequencyHz', ...
        'savedNotchQualityFactor', ...
        'savedUseNormalizedProjection', ...
        '-v7.3');

end


%% ------------------------------------------------------------
% Validate scores
% ------------------------------------------------------------

if any(~isfinite(singleChannelScores(:)))

    error('NaN/Inf found in single-channel scores.');

end


if any(singleChannelScores(:) < 0)

    error('Negative LEAPD score found.');

end


% Geometric-mean classification is done in log-space.
% A true zero score is represented by realmin only for numerical logging;
% the predicted class is unchanged.
logScores = ...
    log(max(singleChannelScores, realmin('double')));


fprintf('Score matrix: %d channels x %d subjects\n', ...
    size(singleChannelScores,1), ...
    size(singleChannelScores,2));


%% ============================================================
% CREATE / LOAD EXACT 10,000 BALANCED REPEATS
%
% Each repeat:
%
%   13 TBI
%   13 Control
%
% All controls are fixed.
% 13 TBI are randomly sampled.
% ============================================================

fprintf('\n============================================================\n');
fprintf('BALANCED OOS SUBSETS\n');
fprintf('============================================================\n');


if isfile(subsetFile)

    fprintf('Loading existing enhanced subset file...\n');

    S = load(subsetFile);


    if ~isequal( ...
            string(S.savedSubjectIDs(:)), ...
            string(testSubjectIDs(:)))

        error('Balanced subset subject-order mismatch.');

    end


    selectedTBIRows = ...
        S.selectedTBIRows;


    fixedControlRows = ...
        S.fixedControlRows;


else

    rng(randomSeed);


    selectedTBIRows = ...
        zeros( ...
            numberOfRepeats, ...
            subjectsPerClass);


    for r = 1:numberOfRepeats

        localSelection = ...
            randperm( ...
                nTBI, ...
                subjectsPerClass);


        selectedTBIRows(r,:) = ...
            tbiRows(localSelection);

    end


    fixedControlRows = ...
        controlRows(:)';


    savedSubjectIDs = ...
        testSubjectIDs;


    save( ...
        subsetFile, ...
        'selectedTBIRows', ...
        'fixedControlRows', ...
        'savedSubjectIDs', ...
        'numberOfRepeats', ...
        'subjectsPerClass', ...
        'randomSeed', ...
        '-v7.3');

end


fprintf('Repeats: %d\n', size(selectedTBIRows,1));


%% ============================================================
% SUBJECT WEIGHTS
%
% Mean accuracy over all 10,000 balanced repeats can be written
% exactly as weighted subject-level correctness.
%
% Therefore we do NOT loop through 10,000 repeats during search.
% ============================================================

subjectUseCounts = ...
    zeros(numel(testClasses),1);


for r = 1:size(selectedTBIRows,1)

    subjectUseCounts(selectedTBIRows(r,:)) = ...
        subjectUseCounts(selectedTBIRows(r,:)) + 1;

end


subjectUseCounts(fixedControlRows) = ...
    size(selectedTBIRows,1);


totalDecisions = ...
    size(selectedTBIRows,1) * ...
    (subjectsPerClass + numel(fixedControlRows));


subjectWeights = ...
    subjectUseCounts / totalDecisions;


if abs(sum(subjectWeights) - 1) > 1e-12

    error('Subject weights do not sum to one.');

end


fprintf('Weighted search objective prepared.\n');


%% ============================================================
% SEARCH STORAGE
% ============================================================

topBySize = ...
    cell(10,1);


bestBySize = ...
    cell(10,1);


%% ============================================================
% EXACT SIZE 1
% ============================================================

fprintf('\n============================================================\n');
fprintf('EXACT SEARCH: 1 CHANNEL\n');
fprintf('============================================================\n');


combos = ...
    (1:nChannels)';


results = ...
    evaluate_binary_combinations( ...
        combos, ...
        logScores, ...
        testClasses, ...
        subjectWeights, ...
        channelNames, ...
        batchSize);


results = ...
    sortrows( ...
        results, ...
        'MeanAccuracy', ...
        'descend');


topBySize{1} = ...
    retain_beam_with_ties( ...
        results, ...
        beamWidth, ...
        maximumBeamRetained, ...
        tieTolerance);


bestBySize{1} = ...
    make_binary_best_row( ...
        1, ...
        results(1,:), ...
        "Exhaustive");


show_binary_winner(1,results(1,:));


%% ============================================================
% EXACT SIZE 2-4
% ============================================================

for combinationSize = 2:4

    fprintf('\n============================================================\n');
    fprintf('EXACT SEARCH: %d CHANNELS\n', combinationSize);
    fprintf('============================================================\n');


    combos = ...
        nchoosek( ...
            1:nChannels, ...
            combinationSize);


    fprintf('Combinations: %d\n', size(combos,1));


    results = ...
        evaluate_binary_combinations( ...
            combos, ...
            logScores, ...
            testClasses, ...
            subjectWeights, ...
            channelNames, ...
            batchSize);


    results = ...
        sortrows( ...
            results, ...
            'MeanAccuracy', ...
            'descend');


    topBySize{combinationSize} = ...
        retain_beam_with_ties( ...
            results, ...
            beamWidth, ...
            maximumBeamRetained, ...
            tieTolerance);


    bestBySize{combinationSize} = ...
        make_binary_best_row( ...
            combinationSize, ...
            results(1,:), ...
            "Exhaustive");


    show_binary_winner( ...
        combinationSize, ...
        results(1,:));

end


%% ============================================================
% EXACT SIZE 5 - MEMORY SAFE
% ============================================================

fprintf('\n============================================================\n');
fprintf('EXACT SEARCH: 5 CHANNELS - MEMORY SAFE\n');
fprintf('============================================================\n');


top5 = ...
    exhaustive_five_binary( ...
        logScores, ...
        testClasses, ...
        subjectWeights, ...
        channelNames, ...
        beamWidth, ...
        maximumBeamRetained, ...
        tieTolerance, ...
        batchSize);


topBySize{5} = ...
    top5;


bestBySize{5} = ...
    make_binary_best_row( ...
        5, ...
        top5(1,:), ...
        "Exhaustive");


show_binary_winner( ...
    5, ...
    top5(1,:));


%% ============================================================
% ENHANCED BEAM SEARCH 6-10
% ============================================================

for combinationSize = 6:10

    fprintf('\n============================================================\n');
    fprintf('ENHANCED BEAM SEARCH: %d CHANNELS\n', combinationSize);
    fprintf('============================================================\n');


    previousTop = ...
        topBySize{combinationSize-1};


    candidateCombos = ...
        expand_binary_beam( ...
            previousTop, ...
            nChannels);


    fprintf( ...
        'Unique candidates: %d\n', ...
        size(candidateCombos,1));


    results = ...
        evaluate_binary_combinations( ...
            candidateCombos, ...
            logScores, ...
            testClasses, ...
            subjectWeights, ...
            channelNames, ...
            batchSize);


    results = ...
        sortrows( ...
            results, ...
            'MeanAccuracy', ...
            'descend');


    topBySize{combinationSize} = ...
        retain_beam_with_ties( ...
            results, ...
            beamWidth, ...
            maximumBeamRetained, ...
            tieTolerance);


    fprintf( ...
        'Beam retained: %d\n', ...
        height(topBySize{combinationSize}));


    bestBySize{combinationSize} = ...
        make_binary_best_row( ...
            combinationSize, ...
            results(1,:), ...
            "EnhancedBeam");


    show_binary_winner( ...
        combinationSize, ...
        results(1,:));

end


%% ============================================================
% STAGE 1:
% ONE-SWAP LOCAL OPTIMIZATION
% TOP 100 TEN-CHANNEL BEAM SOLUTIONS
% ============================================================

fprintf('\n============================================================\n');
fprintf('STAGE 1: ONE-SWAP LOCAL SEARCH\n');
fprintf('============================================================\n');


nStart = ...
    min( ...
        localSwapTopN, ...
        height(topBySize{10}));


startSolutions = ...
    topBySize{10}(1:nStart,:);


oneSwapCells = ...
    cell(nStart,1);


if useParallel

    parfor i = 1:nStart

        oneSwapCells{i} = ...
            iterative_one_swap_binary( ...
                startSolutions.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

else

    for i = 1:nStart

        oneSwapCells{i} = ...
            iterative_one_swap_binary( ...
                startSolutions.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

end


oneSwapResults = ...
    vertcat(oneSwapCells{:});


oneSwapResults = ...
    unique_binary_solutions(oneSwapResults);


oneSwapResults = ...
    sortrows( ...
        oneSwapResults, ...
        'MeanAccuracy', ...
        'descend');


fprintf( ...
    'Unique one-swap local optima: %d\n', ...
    height(oneSwapResults));


fprintf( ...
    'Best after one-swap: %.6f%%\n', ...
    100*oneSwapResults.MeanAccuracy(1));


%% ============================================================
% STAGE 2:
% TWO-CHANNEL SWAP AROUND TOP LOCAL OPTIMA
%
% For a 10-channel set from 60:
%
% C(10,2) * C(50,2)
% = 55,125 neighbors per starting solution.
% ============================================================

fprintf('\n============================================================\n');
fprintf('STAGE 2: TWO-SWAP SEARCH\n');
fprintf('============================================================\n');


nTwoSwapStarts = ...
    min( ...
        twoSwapTopN, ...
        height(oneSwapResults));


twoSwapCells = ...
    cell(nTwoSwapStarts,1);


if useParallel

    parfor i = 1:nTwoSwapStarts

        twoSwapCells{i} = ...
            best_two_swap_binary( ...
                oneSwapResults.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

else

    for i = 1:nTwoSwapStarts

        twoSwapCells{i} = ...
            best_two_swap_binary( ...
                oneSwapResults.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

end


twoSwapResults = ...
    vertcat(twoSwapCells{:});


twoSwapResults = ...
    unique_binary_solutions(twoSwapResults);


twoSwapResults = ...
    sortrows( ...
        twoSwapResults, ...
        'MeanAccuracy', ...
        'descend');


fprintf( ...
    'Best after two-swap: %.6f%%\n', ...
    100*twoSwapResults.MeanAccuracy(1));


%% ============================================================
% STAGE 3:
% FINAL ONE-SWAP FROM EACH TWO-SWAP RESULT
% ============================================================

fprintf('\n============================================================\n');
fprintf('STAGE 3: FINAL ONE-SWAP\n');
fprintf('============================================================\n');


finalSwapCells = ...
    cell(height(twoSwapResults),1);


if useParallel

    parfor i = 1:height(twoSwapResults)

        finalSwapCells{i} = ...
            iterative_one_swap_binary( ...
                twoSwapResults.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

else

    for i = 1:height(twoSwapResults)

        finalSwapCells{i} = ...
            iterative_one_swap_binary( ...
                twoSwapResults.ChannelIndices{i}, ...
                logScores, ...
                testClasses, ...
                subjectWeights, ...
                channelNames, ...
                batchSize);

    end

end


finalRefinementResults = ...
    vertcat(finalSwapCells{:});


finalRefinementResults = ...
    unique_binary_solutions( ...
        finalRefinementResults);


finalRefinementResults = ...
    sortrows( ...
        finalRefinementResults, ...
        'MeanAccuracy', ...
        'descend');


best10Refined = ...
    finalRefinementResults(1,:);


fprintf('\nBEST REFINED 10-CHANNEL COMBINATION\n');

fprintf('%s\n', ...
    best10Refined.Channels);

fprintf( ...
    'Weighted Mean Accuracy = %.6f%%\n', ...
    100*best10Refined.MeanAccuracy);


%% ============================================================
% REPLACE SIZE-10 WINNER IF REFINEMENT IMPROVED IT
