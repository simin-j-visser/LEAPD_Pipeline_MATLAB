function metrics = evaluate_binary_repeats( ...
    combo, ...
    logScores, ...
    trueClasses, ...
    selectedTBIRows, ...
    controlRows)

    combinedLogScore = ...
        sum( ...
            logScores(combo,:), ...
            1);


    threshold = ...
        numel(combo) * log(0.5);


    predictions = ...
        double( ...
            combinedLogScore > threshold);


    nRepeats = ...
        size(selectedTBIRows,1);


    accuracy = ...
        nan(nRepeats,1);


    sensitivity = ...
        nan(nRepeats,1);


    specificity = ...
        nan(nRepeats,1);


    for r = 1:nRepeats

        rows = ...
            [ ...
                selectedTBIRows(r,:), ...
                controlRows ...
            ];


        truth = ...
            trueClasses(rows);


        pred = ...
            predictions(rows)';


        TP = ...
            sum( ...
                truth == 1 & ...
                pred == 1);


        TN = ...
            sum( ...
                truth == 0 & ...
                pred == 0);


        FP = ...
            sum( ...
                truth == 0 & ...
                pred == 1);


        FN = ...
            sum( ...
                truth == 1 & ...
                pred == 0);


        accuracy(r) = ...
            (TP+TN)/numel(rows);


        sensitivity(r) = ...
            TP/(TP+FN);


        specificity(r) = ...
            TN/(TN+FP);

    end


    %% Error fraction for each balanced repeat.
    % Example: 20%% error is stored as 0.20, not 20.
    errorFraction = ...
        1 - accuracy;


    metrics.MeanAccuracy = ...
        mean(accuracy);


    metrics.MeanErrorFraction = ...
        mean(errorFraction);


    metrics.SDErrorFraction = ...
        std(errorFraction);


    metrics.MeanSensitivity = ...
        mean(sensitivity);


    metrics.SDSensitivity = ...
        std(sensitivity);


    metrics.MeanSpecificity = ...
        mean(specificity);


    metrics.SDSpecificity = ...
        std(specificity);


    metrics.MinimumAccuracy = ...
        min(accuracy);


    metrics.MaximumAccuracy = ...
        max(accuracy);

end


