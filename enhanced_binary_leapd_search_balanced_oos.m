%% ============================================================
% ENHANCED BINARY LEAPD OOS CHANNEL SEARCH
%
% Binary mapping:
%   Class 1 = TBI
%   Class 0 = Control
%
% LEAPD score:
%   score > 0.5  -> TBI
%   score <= 0.5 -> Control
%
% Search strategy:
%
%   1-4 channels:
%       exact exhaustive
%
%   5 channels:
%       exact exhaustive, memory-safe
%
%   6-10 channels:
%       wide beam search
%       beamWidth = 1000
%       tie-aware retention
%
%   10-channel refinement:
%       top 100 beam solutions
%           ->
%       iterative 1-channel swap
%           ->
%       deduplicate local optima
%           ->
%       exhaustive 2-channel swap around top 20
%           ->
%       final iterative 1-channel swap
%
% IMPORTANT:
%   This changes ONLY the search strategy.
%   LEAPD feature extraction/model/scoring are unchanged.
%
% Search objective:
%   Mean balanced OOS accuracy over the 10,000 repeats.
%
% For speed, the search uses the mathematically equivalent
% weighted-subject representation of the 10,000 repeats.
%
% Final reported metrics are calculated explicitly across
% all 10,000 balanced repeats.
% ============================================================


%% ============================================================
% SELECT DATASET
% ============================================================

% analysisMode = "acute";
